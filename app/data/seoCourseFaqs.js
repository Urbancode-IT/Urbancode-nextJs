function toQaPairs(list) {
  return (list || []).map((item) => ({
    q: item.q || item.question,
    a: item.a || item.answer,
    question: item.question || item.q,
    answer: item.answer || item.a,
    highlight: item.highlight,
  }));
}

export function getCategoryFaqList(categorySlug) {
  const key = categorySlug && categoryFaqs[categorySlug] ? categorySlug : "default";
  return toQaPairs(categoryFaqs[key] || categoryFaqs.default);
}

